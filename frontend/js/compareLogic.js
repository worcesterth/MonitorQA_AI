/**
 * ตรรกะเปรียบเทียบผล 1 เกณฑ์ (หรือภาพรวม) ระหว่างครั้งปัจจุบันกับ baseline
 * พอร์ตตรงจากสคริปต์ที่ผู้ใช้ให้มา (bPass/cPass/drift/qtype)
 *
 * qtype: ทุกเกณฑ์ในระบบนี้สรุปผลเป็น Pass/Fail เสมอ (ไม่มีเกณฑ์แบบตัวเลขล้วนที่ไม่ผ่าน/ไม่ผ่านคู่แล้ว
 * ต้องเทียบค่าต่อ) จึงกำหนด qtype = "yes_no" ตายตัว — ถ้าภายหลังมีเกณฑ์แบบอื่นเพิ่ม ต้องเติม branch
 * qtype อื่นในฟังก์ชันนี้
 *
 * drift: "A" ถ้าผู้ประเมิน (tested_by) เป็นคนเดียวกันทั้ง baseline และครั้งนี้ (ไม่แน่ใจสาเหตุ จึงใช้คำว่า
 * "อาจเกิดจาก...") / "B" ถ้าเปลี่ยนผู้ประเมิน (มั่นใจกว่า จึงใช้คำว่า "เนื่องมาจาก...")
 */
export function compareOutcome(bPass, cPass, drift, qtype = "yes_no") {
  // ทั้งคู่ผ่าน
  if (bPass && cPass) {
    const desc = "ผลที่ได้จากการทดสอบ ครั้งนี้ และผลที่ได้จาก baseline ผ่านเกณฑ์ทั้งคู่";
    return { verdict: "คุณภาพของหน้าจอเท่าเดิม", code: "same", desc };
  }

  // baseline ผ่าน ปัจจุบันไม่ผ่าน
  if (bPass && !cPass) {
    const desc = "ผลที่ได้จากการทดสอบ ครั้งนี้ ไม่ผ่านเกณฑ์และผลที่ได้จาก baseline ผ่านเกณฑ์";
    return { verdict: "คุณภาพของหน้าจอลดลง", code: "degraded", desc };
  }

  // baseline ไม่ผ่าน ปัจจุบันผ่าน
  if (!bPass && cPass) {
    const desc = "ผลที่ได้จากการทดสอบ ครั้งนี้ ผ่านเกณฑ์และผลที่ได้จาก baseline ไม่ผ่านเกณฑ์";
    if (drift === "A") {
      return { verdict: "ผลการทดสอบคลาดเคลื่อนอาจเกิดจากการเปลี่ยนผู้ประเมินหรือปัจจัยอื่นที่เกี่ยวข้อง", code: "drift", desc };
    }
    return { verdict: "ผลการทดสอบคลาดเคลื่อนเนื่องมาจากมีการเปลี่ยนผู้ประเมินและปัจจัยที่เกี่ยวข้องอื่น ๆ", code: "drift", desc };
  }

  // ทั้งคู่ไม่ผ่าน
  if (qtype === "yes_no") {
    const desc = "ผลการประเมินไม่ผ่านทั้งคู่";
    return { verdict: "คุณภาพของหน้าจอเท่าเดิม", code: "same", desc };
  }

  // fallback เผื่อ qtype อื่นในอนาคต (ยังไม่มีในระบบนี้)
  const desc = "ผลการประเมินไม่ผ่านทั้งคู่";
  return { verdict: "คุณภาพของหน้าจอเท่าเดิม", code: "same", desc };
}
